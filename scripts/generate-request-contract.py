#!/usr/bin/env python3
"""Derive wire guards from the signed source, never a hand-maintained field list."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    spec = json.loads((ROOT / "spec/openapi.json").read_text())

    def constraints(schema, seen=()):
        if "$ref" in schema:
            name = schema["$ref"].split("/")[-1]
            if name in seen:
                raise SystemExit(f"recursive request schema needs explicit support: {name}")
            return constraints(spec["components"]["schemas"][name], (*seen, name))
        result = {key: schema[key] for key in ("type", "enum", "additionalProperties") if key in schema and (key != "additionalProperties" or schema[key] is False)}
        for key in ("anyOf", "oneOf", "allOf"):
            if key in schema:
                result[key] = [constraints(child, seen) for child in schema[key]]
        if "properties" in schema:
            result["properties"] = {key: constraints(child, seen) for key, child in schema["properties"].items()}
        if "items" in schema:
            result["items"] = constraints(schema["items"], seen)
        if isinstance(schema.get("additionalProperties"), dict):
            result["additionalProperties"] = constraints(schema["additionalProperties"], seen)
        return result

    routes = []
    for path, item in spec["paths"].items():
        for method, operation in item.items():
            if not isinstance(operation, dict):
                continue
            body = operation.get("requestBody", {}).get("content", {}).get("application/json", {})
            if "schema" in body:
                routes.append({"method": method.upper(), "path": path, "schema": constraints(body["schema"])})
    encoded = json.dumps(routes, separators=(",", ":"), sort_keys=True)
    output = args.output / "request_contract_generated.go"
    output.write_text('// Code generated by scripts/generate-request-contract.py; DO NOT EDIT.\npackage plainrouter\n\nconst requestContractJSON = ' + json.dumps(encoded) + '\n')
    print(f"Derived wire constraints for {len(routes)} request operations")


if __name__ == "__main__":
    main()
